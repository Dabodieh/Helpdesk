using NpgsqlTypes;

namespace Helpdesk.Modules.Knowledge.Domain;

internal static class ArticleStatuses
{
    public const string Draft = "Draft";
    public const string Published = "Published";
    public const string Archived = "Archived";
}

internal static class ArticleVisibility
{
    /// <summary>Every signed-in employee.</summary>
    public const string Everyone = "Everyone";

    /// <summary>Only people who are requesters in the article's department (they have raised, or been recorded on, a request there).</summary>
    public const string Requesters = "Requesters";

    public static readonly string[] All = [Everyone, Requesters];
}

/// <summary>A shallow (one level) grouping of a department's articles.</summary>
internal sealed class KnowledgeCategory
{
    public Guid Id { get; set; }

    public Guid DepartmentId { get; set; }

    public string Name { get; set; } = "";

    public string? Description { get; set; }

    public int SortOrder { get; set; }

    public bool IsActive { get; set; } = true;

    public DateTimeOffset CreatedAt { get; set; }

    public DateTimeOffset UpdatedAt { get; set; }

    public uint Version { get; set; }
}

/// <summary>
/// An article with two separate content slots. Requesters only ever read the <b>published</b> slot; editing writes the <b>draft</b> slot, so a half-edited
/// article of a published page is never public. Publishing copies draft to published in one step.
/// </summary>
internal sealed class KnowledgeArticle
{
    public Guid Id { get; set; }

    public Guid DepartmentId { get; set; }

    public Guid? CategoryId { get; set; }

    /// <summary>Stable URL segment, unique across the knowledge base; never changes after creation.</summary>
    public string Slug { get; set; } = "";

    public string Status { get; set; } = ArticleStatuses.Draft;

    public string Visibility { get; set; } = ArticleVisibility.Everyone;

    public string DraftTitle { get; set; } = "";

    public string DraftSummary { get; set; } = "";

    /// <summary>Markdown source (rendered by the client without raw HTML).</summary>
    public string DraftBody { get; set; } = "";

    public DateTimeOffset DraftUpdatedAt { get; set; }

    public Guid? DraftUpdatedByUserId { get; set; }

    public string? PublishedTitle { get; set; }

    public string? PublishedSummary { get; set; }

    public string? PublishedBody { get; set; }

    public DateTimeOffset? PublishedAt { get; set; }

    public Guid? PublishedByUserId { get; set; }

    public Guid AuthorUserId { get; set; }

    public DateTimeOffset CreatedAt { get; set; }

    public DateTimeOffset UpdatedAt { get; set; }

    /// <summary>Generated by PostgreSQL from the PUBLISHED slot only: a draft can never match a search.</summary>
    public NpgsqlTsVector SearchVector { get; set; } = null!;

    public uint Version { get; set; }
}

/// <summary>One person's "helpful / not helpful" answer for an article (the latest answer wins).</summary>
internal sealed class ArticleFeedback
{
    public Guid ArticleId { get; set; }

    public Guid UserId { get; set; }

    public bool Helpful { get; set; }

    public DateTimeOffset UpdatedAt { get; set; }
}
